import { chromium, devices } from '@playwright/test';
const SP = process.env.SHOT_DIR;
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ ...devices['iPhone 13'], isMobile: true, hasTouch: true, viewport: { width: 844, height: 390 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const logs = [];
page.on('pageerror', (e) => logs.push('PAGEERROR ' + e.message));
await page.goto('http://localhost:4173/');
await page.waitForTimeout(800);
await page.screenshot({ path: `${SP}/shots/m-title.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(300);
await page.screenshot({ path: `${SP}/shots/m-title-portrait.png` });
await page.setViewportSize({ width: 844, height: 390 });
await page.uncheck('#opt-sound');
await page.tap('#btn-start');
await page.waitForFunction(() => window.__bali.game && window.__bali.game.started, null, { timeout: 300000 });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${SP}/shots/m-game.png` });
console.log(logs.join('\n'));
await browser.close();
